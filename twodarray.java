public class twodarray {
    //sum of rows, sum of columns, sum of two array, sum of elememnts
    public static void main(String[] args) {
        int ar[][] = {{1,2},{3,4}};
        for(int i=0; i<2; i++){
            for(int j=0; j<2; j++){
                System.out.print(ar[i][j] + " ");
            }
            System.out.println();
        }
    }

}
